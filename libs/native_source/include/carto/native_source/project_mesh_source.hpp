#pragma once

#include <carto/engineering/topology_correspondence.hpp>
#include <carto/geometry/compiled_mesh.hpp>
#include <carto/project/project.hpp>
#include <carto/render/render_scene.hpp>

namespace carto::native_source {

// A candidate built from one selected project instance. Its projection is a
// native source manifest, not a STEP file or a parametric feature history.
// The production render bytes and physical CompiledMesh have distinct digest
// domains. No physical, engineering or consumer admission is implied.
struct ProjectMeshSource {
    std::string source_projection;
    std::string source_namespace;
    assets::Sha256Digest source_digest;
    core::Revision observed_project_revision;
    // Observed context only; scene revision is reconstructed on project load.
    core::Revision scene_revision;
    core::Revision mesh_revision;
    scene::ObjectId object;
    std::uint64_t mesh_asset = 0U;
    core::Transform local_to_project_world;
    assets::Sha256Digest editable_mesh_digest;
    geometry::CompiledMesh physical_mesh_candidate;
    std::vector<std::uint8_t> render_mesh_bytes;
    assets::Sha256Digest render_mesh_digest;
    // The generated bytes are not yet registered or resolved through the
    // project's mesh asset. Correspondence below is a candidate until the
    // display owner establishes that exact asset/revision/byte binding.
    [[nodiscard]] constexpr bool render_asset_binding_verified() const noexcept { return false; }
    engineering::EngineeringPart part;
    engineering::EngineeringOccurrence occurrence;
    std::vector<engineering::TopologyBinding> faces;
    // These are detached-artifact candidates, not a usable picking map.
    // The display owner must first bind the actual artifact and then construct
    // and admit its own TopologyCorrespondenceMap.
    std::vector<engineering::DisplayTriangleBinding> render_face_candidates;
};

// Caller must not concurrently mutate project during the snapshot copy. The
// initial scope is a root object with rigid transform and an attached mesh.
// This mutable result is not an admission receipt. Consumers must rederive the
// complete result from authoritative current project state and use that fresh
// result, rather than trusting a supplied projection, map or mesh bytes.
[[nodiscard]] core::Result<ProjectMeshSource> derive_project_mesh_source(
    const project::ProjectDocument& project, scene::ObjectId selected_object);

// Point-in-time structural binding to an owner-supplied viewport scene. This
// mutable value is not a durable receipt or proof of a gesture, displayed
// pixels or admission; the owner must enforce live-source/generation/selection
// authority and rederive against current inputs before use.
struct ProjectViewportFace {
    scene::ObjectId object;
    std::uint64_t mesh_asset = 0U;
    geometry::FaceId face;
    assets::Sha256Digest source_digest;
    engineering::TopologyIdentityKey topology;
    assets::Sha256Digest persistent_topology;
    std::vector<std::uint32_t> compiled_triangles;
};

// The caller supplies the owner-controlled viewport scene and must prevent
// concurrent mutation of both inputs during this call. Every mesh field and
// the selected occurrence's world transform are checked against current source.
[[nodiscard]] core::Result<ProjectViewportFace> verify_project_viewport_face(
    const project::ProjectDocument& project, const render::RenderScene& viewport,
    scene::ObjectId selected_object, geometry::FaceId face);

} // namespace carto::native_source
